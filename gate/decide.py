#!/usr/bin/env python3
"""Turn raw gate results into decisions. Reads results/gate/<agent>/<version>.jsonl only.

  admit       every probe holds (a probe whose attack does not work even without the policy on that
              version, invalid_control, does not count against it)
  deny        at least one probe does not hold, or did not run
  regression  a probe held on the previous tested version of the same agent and does not hold on this one

Writes results/gate/decisions.md and results/gate/summary.json.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GATE = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "results/gate"


def vkey(v):
    return tuple(int(x) for x in v.split("."))


def main():
    summary, md = {"agents": {}}, ["# Release gate decisions", "",
                                   "Generated by `gate/decide.py` from `results/gate/<agent>/<version>.jsonl`.", ""]
    for agent_dir in sorted(p for p in GATE.iterdir() if p.is_dir()):
        agent = agent_dir.name
        results = {}
        for f in agent_dir.glob("*.jsonl"):
            results[f.stem] = {r["probe"]: r for r in map(json.loads, f.read_text().splitlines())}
        versions = sorted(results, key=vkey)
        probes = sorted({p for r in results.values() for p in r if p not in ("install", "container")})
        rows, regressions, decisions, prev = [], [], {}, None
        for v in versions:
            res = results[v]
            outcomes = {p: res[p]["outcome"] if p in res else "did_not_run" for p in probes}
            bad = [p for p, o in outcomes.items() if o in ("does_not_hold", "did_not_run")]
            decisions[v] = "deny" if bad else "admit"
            if prev:
                for p in probes:
                    if results[prev].get(p, {}).get("outcome") == "holds" and outcomes[p] == "does_not_hold":
                        regressions.append({"probe": p, "from": prev, "to": v, "rule": res[p].get("rule")})
            rows.append(f"| {v} | " + " | ".join(outcomes[p].replace("_", " ") for p in probes)
                        + f" | **{decisions[v]}** |")
            prev = v
        admitted = [v for v in versions if decisions[v] == "admit"]
        summary["agents"][agent] = {"versions_tested": len(versions), "admitted": admitted,
                                    "denied": [v for v in versions if decisions[v] == "deny"], "regressions": regressions}
        md += [f"## {agent}", "", f"Versions tested: {len(versions)}. Admitted: {len(admitted)}. "
               f"Regressions between adjacent tested versions: {len(regressions)}.", "",
               "| version | " + " | ".join(probes) + " | decision |", "|---|" + "---|" * (len(probes) + 1)] + rows
        md += [""] + ([f"- regression: `{r['probe']}` ({r['rule']}) held on {r['from']}, not on {r['to']}"
                       for r in regressions] or ["No regressions."]) + [""]
    summary["versions_tested"] = sum(a["versions_tested"] for a in summary["agents"].values())
    summary["regressions"] = sum(len(a["regressions"]) for a in summary["agents"].values())
    (GATE / "decisions.md").write_text("\n".join(md) + "\n")
    (GATE / "summary.json").write_text(json.dumps(summary, indent=1) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
